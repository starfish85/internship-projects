def _sub_token(text: str, ko: str, zh: str) -> str:
    if not ko:
        return text
    if re.search(r"[A-Za-z0-9]", ko) or any(ch in ko for ch in " /&+·∙・→↔⇄<>()[]"):
        return text.replace(ko, zh)
    return re.sub(rf"(?<![가-힣]){re.escape(ko)}(?![가-힣])", zh, text)


def translate_ko(text: str | None) -> str:
    if not text:
        return ""
    src = str(text).strip()
    if not src:
        return ""
    if src in CATEGORY_ZH:
        return CATEGORY_ZH[src]
    if src in CITY_ZH:
        return CITY_ZH[src]

    out = src
    phrases = sorted(PHRASES, key=lambda x: len(x[0]), reverse=True)
    for ko, zh in phrases:
        if ko and ko in out:
            out = _sub_token(out, ko, zh)
    for ko, zh in sorted(list(CITY_ZH.items()) + WORDS, key=lambda x: len(x[0]), reverse=True):
        if ko and ko in out:
            out = _sub_token(out, ko, zh)

    out = re.sub(r"키\s*(\d+)\s*cm", r"身高\1cm", out)
    out = re.sub(r"(\d+)\s*인승", r"\1座", out)
    out = re.sub(r"(\d+)\s*시간", r"\1小时", out)
    out = re.sub(r"([一-龥A-Za-z0-9]+)\s*행", r"开往\1", out)
    out = re.sub(r"([一-龥]{2,})에서", r"从\1", out)
    out = re.sub(r"까지", "至", out)
    out = re.sub(r"\s{2,}", " ", out).strip()
    out = out.replace("门票 门票", "门票")
    return out


def translate_list(items: List[str], joiner: str = " / ") -> Tuple[str, str]:
    ko = joiner.join([x for x in items if x])
    zh_parts = []
    seen = set()
    for x in items:
        if not x:
            continue
        z = translate_ko(x)
        if z and z not in seen:
            seen.add(z)
            zh_parts.append(z)
    return ko, joiner.join(zh_parts)
